#!/usr/bin/env bash
# gen-stubs.sh <cargo build log>...  — add a weak, aborting definition to shim/ffi_stubs.c for
# every `undefined symbol:` lld reported. These are link-time dispatch hooks
# (`__bun_dispatch__*`) and FFI that only higher-tier crates or the full bun binary provide. Weak, so
# a real definition always wins; a test that actually reaches one dies naming the symbol (the
# analogue of Miri's "can't call foreign function").
set -euo pipefail
cd "$(dirname "$0")"
F=shim/ffi_stubs.c
[ -f $F ] || printf '%s\n' '// GENERATED by gen-stubs.sh' '#include <stdio.h>' '#include <stdlib.h>' \
  '#define STUB(name) __attribute__((weak, noreturn)) void name(void) { fprintf(stderr, "bsan-bun: test reached unprovided FFI/dispatch symbol `%s`\n", #name); abort(); }' > $F
new=0
for sym in $(grep -ohE "undefined symbol: [A-Za-z_][A-Za-z0-9_]*" "$@" | awk '{print $3}' | sort -u); do
  grep -q "^STUB($sym)$" $F || { echo "STUB($sym)" >> $F; new=$((new+1)); }
done
echo "added $new stubs ($(grep -c '^STUB(' $F) total)"
